-- 101-内容素材与授权.sql
-- 目的：建立内容获客 P0-1 素材库与三层授权底座。
-- 影响表：新增 db_content_asset、db_content_authorization。
-- 说明：P0 素材必须关联项目，便于复用现有项目权限；客户/员工授权主体通过 subject_ref_id 记录。
-- 回滚：
-- DROP TABLE IF EXISTS db_content_authorization;
-- DROP TABLE IF EXISTS db_content_asset;

CREATE TABLE db_content_asset (
    asset_id BIGINT NOT NULL COMMENT '素材索引',
    com_id BIGINT NOT NULL COMMENT '所属企业',
    store_id BIGINT NULL COMMENT '所属门店',
    project_id BIGINT NOT NULL COMMENT '所属项目',
    customer_id BIGINT NULL COMMENT '关联客户',
    uploader_id BIGINT NOT NULL COMMENT '上传员工',
    title VARCHAR(255) NOT NULL COMMENT '素材标题',
    media_type VARCHAR(16) NOT NULL COMMENT '媒体类型',
    source_type VARCHAR(16) NOT NULL COMMENT '素材来源',
    truth_type VARCHAR(16) NOT NULL COMMENT '真实性类型',
    file_path VARCHAR(512) NOT NULL COMMENT '私有文件路径',
    original_name VARCHAR(255) NULL COMMENT '原始文件名',
    content_type VARCHAR(128) NULL COMMENT '文件类型',
    file_size BIGINT NULL COMMENT '文件大小',
    tags VARCHAR(2000) NULL COMMENT '标签，逗号分隔',
    desensitized TINYINT(1) NOT NULL DEFAULT 0 COMMENT '是否完成脱敏',
    status VARCHAR(24) NOT NULL COMMENT '素材状态',
    remark VARCHAR(1000) NULL COMMENT '备注',
    data_version INT NOT NULL DEFAULT 1 COMMENT '数据版本',
    create_date_time DATETIME(6) NULL,
    create_date DATE NULL,
    create_time TIME NULL,
    create_year INT NULL,
    create_month INT NULL,
    create_day INT NULL,
    create_hour INT NULL,
    create_minute INT NULL,
    create_second INT NULL,
    create_week INT NULL,
    update_date_time DATETIME(6) NULL,
    update_date DATE NULL,
    update_time TIME NULL,
    update_year INT NULL,
    update_month INT NULL,
    update_day INT NULL,
    update_hour INT NULL,
    update_minute INT NULL,
    update_second INT NULL,
    update_week INT NULL,
    PRIMARY KEY (asset_id),
    KEY idx_content_asset_company (com_id, asset_id),
    KEY idx_content_asset_company_project (com_id, project_id, asset_id),
    KEY idx_content_asset_company_status (com_id, status, asset_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='内容素材';

CREATE TABLE db_content_authorization (
    auth_id BIGINT NOT NULL COMMENT '授权索引',
    com_id BIGINT NOT NULL COMMENT '所属企业',
    asset_id BIGINT NOT NULL COMMENT '素材',
    subject_type VARCHAR(16) NOT NULL COMMENT '授权主体类型',
    subject_ref_id BIGINT NOT NULL COMMENT '授权主体索引',
    purpose VARCHAR(24) NOT NULL COMMENT '授权用途',
    channels VARCHAR(500) NULL COMMENT '渠道，逗号分隔',
    region VARCHAR(255) NULL COMMENT '授权地域',
    valid_from DATE NOT NULL COMMENT '生效日期',
    valid_to DATE NOT NULL COMMENT '失效日期',
    allow_modify TINYINT(1) NOT NULL DEFAULT 0 COMMENT '允许修改',
    allow_ai TINYINT(1) NOT NULL DEFAULT 0 COMMENT '允许AI处理',
    allow_ads TINYINT(1) NOT NULL DEFAULT 0 COMMENT '允许投流',
    allow_sublicense TINYINT(1) NOT NULL DEFAULT 0 COMMENT '允许转授权',
    evidence_path VARCHAR(512) NULL COMMENT '授权证据文件路径',
    status VARCHAR(16) NOT NULL COMMENT '授权状态',
    revoked_by BIGINT NULL COMMENT '撤回人',
    revoked_at DATETIME(6) NULL COMMENT '撤回时间',
    revoke_reason VARCHAR(500) NULL COMMENT '撤回原因',
    remark VARCHAR(1000) NULL COMMENT '备注',
    create_date_time DATETIME(6) NULL,
    create_date DATE NULL,
    create_time TIME NULL,
    create_year INT NULL,
    create_month INT NULL,
    create_day INT NULL,
    create_hour INT NULL,
    create_minute INT NULL,
    create_second INT NULL,
    create_week INT NULL,
    update_date_time DATETIME(6) NULL,
    update_date DATE NULL,
    update_time TIME NULL,
    update_year INT NULL,
    update_month INT NULL,
    update_day INT NULL,
    update_hour INT NULL,
    update_minute INT NULL,
    update_second INT NULL,
    update_week INT NULL,
    PRIMARY KEY (auth_id),
    KEY idx_content_auth_company (com_id, auth_id),
    KEY idx_content_auth_asset (asset_id, purpose, status),
    KEY idx_content_auth_expiry (com_id, status, valid_to)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='内容素材授权';

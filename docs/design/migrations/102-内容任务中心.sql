CREATE TABLE db_content_template (
    template_id BIGINT NOT NULL COMMENT '模板索引',
    com_id BIGINT NULL COMMENT '所属企业，空为系统模板',
    store_id BIGINT NULL COMMENT '所属门店',
    name VARCHAR(128) NOT NULL COMMENT '模板名称',
    format VARCHAR(16) NOT NULL COMMENT '画幅比例',
    duration_sec INT NOT NULL COMMENT '建议时长秒',
    clip_min INT NOT NULL COMMENT '最少片段数',
    clip_max INT NOT NULL COMMENT '最多片段数',
    script_schema TEXT NULL COMMENT '脚本结构',
    cover_schema TEXT NULL COMMENT '封面结构',
    allowed_asset_types VARCHAR(255) NULL COMMENT '允许的素材类型',
    status VARCHAR(16) NOT NULL COMMENT '模板状态',
    version INT NOT NULL DEFAULT 1 COMMENT '版本',
    create_date_time BIGINT NULL,
    create_date INT NULL,
    create_time INT NULL,
    create_year INT NULL,
    create_month INT NULL,
    create_day INT NULL,
    create_hour INT NULL,
    create_minute INT NULL,
    create_second INT NULL,
    create_week TINYINT NULL,
    update_date_time BIGINT NULL,
    update_date INT NULL,
    update_time INT NULL,
    update_year INT NULL,
    update_month INT NULL,
    update_day INT NULL,
    update_hour INT NULL,
    update_minute INT NULL,
    update_second INT NULL,
    update_week TINYINT NULL,
    PRIMARY KEY (template_id),
    KEY idx_content_template_company (com_id, template_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='内容模板';

CREATE TABLE db_content_task (
    task_id BIGINT NOT NULL COMMENT '任务索引',
    com_id BIGINT NOT NULL COMMENT '所属企业',
    store_id BIGINT NULL COMMENT '所属门店',
    template_id BIGINT NOT NULL COMMENT '内容模板',
    title VARCHAR(255) NOT NULL COMMENT '任务标题',
    goal VARCHAR(32) NOT NULL COMMENT '传播目标',
    target_audience VARCHAR(500) NOT NULL COMMENT '目标人群',
    platform VARCHAR(24) NOT NULL COMMENT '发布平台',
    material_ids TEXT NULL COMMENT '素材ID列表，逗号分隔',
    required_claims TEXT NULL COMMENT '必须表达',
    forbidden_claims TEXT NULL COMMENT '禁止表达',
    deadline DATETIME(6) NOT NULL COMMENT '截止时间',
    assignee_scope VARCHAR(32) NOT NULL COMMENT '分配范围',
    assignee_emp_ids TEXT NULL COMMENT '指定员工ID列表',
    reviewer_id BIGINT NOT NULL COMMENT '审核人',
    lead_owner_id BIGINT NOT NULL COMMENT '线索承接人',
    created_by BIGINT NOT NULL COMMENT '创建人',
    status VARCHAR(24) NOT NULL COMMENT '任务状态',
    published_at DATETIME(6) NULL COMMENT '发布时间',
    closed_at DATETIME(6) NULL COMMENT '关闭时间',
    create_date_time BIGINT NULL,
    create_date INT NULL,
    create_time INT NULL,
    create_year INT NULL,
    create_month INT NULL,
    create_day INT NULL,
    create_hour INT NULL,
    create_minute INT NULL,
    create_second INT NULL,
    create_week TINYINT NULL,
    update_date_time BIGINT NULL,
    update_date INT NULL,
    update_time INT NULL,
    update_year INT NULL,
    update_month INT NULL,
    update_day INT NULL,
    update_hour INT NULL,
    update_minute INT NULL,
    update_second INT NULL,
    update_week TINYINT NULL,
    PRIMARY KEY (task_id),
    KEY idx_content_task_company (com_id, task_id),
    KEY idx_content_task_company_status (com_id, status, task_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='内容任务';

CREATE TABLE db_content_employee_content (
    content_id BIGINT NOT NULL COMMENT '员工内容索引',
    com_id BIGINT NOT NULL COMMENT '所属企业',
    task_id BIGINT NOT NULL COMMENT '内容任务',
    emp_id BIGINT NOT NULL COMMENT '员工',
    status VARCHAR(24) NOT NULL COMMENT '执行状态',
    started_at DATETIME(6) NULL COMMENT '领取时间',
    submitted_at DATETIME(6) NULL COMMENT '提交时间',
    review_status VARCHAR(32) NULL COMMENT '审核状态',
    publish_status VARCHAR(32) NULL COMMENT '发布状态',
    rejection_reason VARCHAR(500) NULL COMMENT '驳回原因',
    create_date_time BIGINT NULL,
    create_date INT NULL,
    create_time INT NULL,
    create_year INT NULL,
    create_month INT NULL,
    create_day INT NULL,
    create_hour INT NULL,
    create_minute INT NULL,
    create_second INT NULL,
    create_week TINYINT NULL,
    update_date_time BIGINT NULL,
    update_date INT NULL,
    update_time INT NULL,
    update_year INT NULL,
    update_month INT NULL,
    update_day INT NULL,
    update_hour INT NULL,
    update_minute INT NULL,
    update_second INT NULL,
    update_week TINYINT NULL,
    PRIMARY KEY (content_id),
    UNIQUE KEY uk_content_employee_task (task_id, emp_id),
    KEY idx_content_employee_company (com_id, content_id),
    KEY idx_content_employee_employee (emp_id, status, content_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='员工内容执行记录';


CREATE TABLE IF NOT EXISTS db_finance_expense_category (
    category_id BIGINT NOT NULL,
    com_id BIGINT NOT NULL,
    code VARCHAR(64) NOT NULL COMMENT '分类编码',
    name VARCHAR(64) NOT NULL COMMENT '分类名称',
    description VARCHAR(500) NULL COMMENT '分类说明',
    built_in BIT NOT NULL DEFAULT 0 COMMENT '是否平台基础分类',
    active BIT NOT NULL DEFAULT 1 COMMENT '是否启用',
    sort_no INT NOT NULL DEFAULT 0 COMMENT '显示排序',
    creator_id BIGINT NULL COMMENT '创建人',
    create_date_time BIGINT NULL, create_date INT NULL, create_time INT NULL, create_year INT NULL,
    create_month INT NULL, create_day INT NULL, create_hour INT NULL, create_minute INT NULL,
    create_second INT NULL, create_week TINYINT NULL,
    update_date_time BIGINT NULL, update_date INT NULL, update_time INT NULL, update_year INT NULL,
    update_month INT NULL, update_day INT NULL, update_hour INT NULL, update_minute INT NULL,
    update_second INT NULL, update_week TINYINT NULL,
    PRIMARY KEY (category_id),
    UNIQUE KEY uk_fin_expense_category_company_code (com_id, code),
    KEY idx_fin_expense_category_company (com_id, category_id),
    KEY idx_fin_expense_category_sort (com_id, active, sort_no),
    CONSTRAINT fk_fin_expense_category_company FOREIGN KEY (com_id) REFERENCES db_tenant_company (com_id),
    CONSTRAINT fk_fin_expense_category_creator FOREIGN KEY (creator_id) REFERENCES db_tenant_employee (emp_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='企业费用分类';

CREATE TABLE IF NOT EXISTS db_finance_expense (
    expense_id BIGINT NOT NULL,
    com_id BIGINT NOT NULL,
    store_id BIGINT NULL COMMENT '归属门店；仅 BOSS/总部财务可提交未归属门店费用',
    team_id BIGINT NULL,
    project_id BIGINT NULL,
    requester_id BIGINT NOT NULL COMMENT '实际提交人',
    owner_id BIGINT NOT NULL COMMENT '费用归属员工/数据负责人',
    payee_emp_id BIGINT NULL COMMENT '报销收款员工',
    category_id BIGINT NOT NULL,
    expense_no VARCHAR(64) NOT NULL,
    payment_mode VARCHAR(24) NOT NULL COMMENT 'Direct/Reimbursement',
    amount DECIMAL(14,2) NOT NULL DEFAULT 0,
    expense_date DATE NOT NULL,
    description LONGTEXT NOT NULL,
    status VARCHAR(24) NOT NULL,
    version INT NOT NULL DEFAULT 0,
    submitted_at DATETIME(6) NULL,
    approved_by_id BIGINT NULL,
    approved_at DATETIME(6) NULL,
    approval_note LONGTEXT NULL,
    self_approved BIT NOT NULL DEFAULT 0,
    voided_by_id BIGINT NULL,
    voided_at DATETIME(6) NULL,
    void_reason VARCHAR(500) NULL,
    source_type VARCHAR(32) NULL,
    source_id BIGINT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    create_date_time BIGINT NULL, create_date INT NULL, create_time INT NULL, create_year INT NULL,
    create_month INT NULL, create_day INT NULL, create_hour INT NULL, create_minute INT NULL,
    create_second INT NULL, create_week TINYINT NULL,
    update_date_time BIGINT NULL, update_date INT NULL, update_time INT NULL, update_year INT NULL,
    update_month INT NULL, update_day INT NULL, update_hour INT NULL, update_minute INT NULL,
    update_second INT NULL, update_week TINYINT NULL,
    PRIMARY KEY (expense_id),
    UNIQUE KEY uk_fin_expense_company_no (com_id, expense_no),
    UNIQUE KEY uk_fin_expense_company_idempotency (com_id, idempotency_key),
    KEY idx_fin_expense_company (com_id, expense_id),
    KEY idx_fin_expense_store_status (com_id, store_id, status, create_date_time),
    KEY idx_fin_expense_requester (com_id, requester_id, create_date_time),
    KEY idx_fin_expense_project (com_id, project_id, expense_date),
    KEY idx_fin_expense_payee (com_id, payee_emp_id, create_date_time),
    KEY idx_fin_expense_owner (com_id, owner_id, create_date_time),
    CONSTRAINT fk_fin_expense_company FOREIGN KEY (com_id) REFERENCES db_tenant_company (com_id),
    CONSTRAINT fk_fin_expense_store FOREIGN KEY (store_id) REFERENCES db_tenant_store (store_id),
    CONSTRAINT fk_fin_expense_team FOREIGN KEY (team_id) REFERENCES db_tenant_team (team_id),
    CONSTRAINT fk_fin_expense_project FOREIGN KEY (project_id) REFERENCES db_project (project_id),
    CONSTRAINT fk_fin_expense_requester FOREIGN KEY (requester_id) REFERENCES db_tenant_employee (emp_id),
    CONSTRAINT fk_fin_expense_owner FOREIGN KEY (owner_id) REFERENCES db_tenant_employee (emp_id),
    CONSTRAINT fk_fin_expense_payee FOREIGN KEY (payee_emp_id) REFERENCES db_tenant_employee (emp_id),
    CONSTRAINT fk_fin_expense_category FOREIGN KEY (category_id) REFERENCES db_finance_expense_category (category_id),
    CONSTRAINT fk_fin_expense_approved FOREIGN KEY (approved_by_id) REFERENCES db_tenant_employee (emp_id),
    CONSTRAINT fk_fin_expense_voided FOREIGN KEY (voided_by_id) REFERENCES db_tenant_employee (emp_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='企业费用与员工报销';


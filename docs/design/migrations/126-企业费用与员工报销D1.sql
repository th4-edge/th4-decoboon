    expense_id BIGINT NOT NULL,
    document_type VARCHAR(32) NOT NULL,
    file_url VARCHAR(512) NOT NULL,
    file_name VARCHAR(255) NULL,
    sha256 VARCHAR(64) NULL,
    file_size BIGINT NULL,

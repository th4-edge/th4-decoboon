-- 54 风险处置单与处置流水（P2.1 风险处置闭环）
-- 依据：docs/product/2026-09-23-风险处置闭环设计方案-P2.1.md（用户 2026-09-23 裁决）
-- 说明：预警由 BusinessAlertContext 实时计算、不落库；本迁移只新增「人对预警的处置事实」两张表。
--       处置单与预警通过稳定键 alert_key = alertType:businessType:businessId 关联，不复制预警内容。

CREATE TABLE IF NOT EXISTS `db_risk_item` (
  `risk_id` BIGINT NOT NULL COMMENT '风险处置单索引（雪花）',
  `com_id` BIGINT NOT NULL COMMENT '所属企业',
  `store_id` BIGINT NULL COMMENT '归属门店',
  `team_id` BIGINT NULL COMMENT '归属团队',
  `owner_id` BIGINT NULL COMMENT '当前处置责任人',
  `alert_key` VARCHAR(160) NOT NULL COMMENT '稳定预警键：alertType:businessType:businessId',
  `alert_type` VARCHAR(40) NOT NULL COMMENT '预警类型',
  `business_type` VARCHAR(40) NULL COMMENT '关联业务对象类型',
  `business_id` BIGINT NULL COMMENT '关联业务对象主键',
  `project_id` BIGINT NULL COMMENT '关联项目',
  `level_at_create` VARCHAR(20) NULL COMMENT '首次出现级别快照',
  `status` VARCHAR(20) NOT NULL COMMENT '待响应/处理中/已关闭/已消解',
  `discovered_at` DATETIME NULL COMMENT '首次发现时间',
  `assigned_at` DATETIME NULL COMMENT '最近指派时间',
  `due_at` DATETIME NULL COMMENT '应处置截止时间（按级别 SLA）',
  `closed_at` DATETIME NULL COMMENT '关闭时间',
  `closed_by` BIGINT NULL COMMENT '关闭人',
  `close_result` VARCHAR(500) NULL COMMENT '处置结果（关闭必填）',
  `round_no` INT NULL DEFAULT 1 COMMENT '重开轮次',
  `recurrence_count` INT NULL DEFAULT 0 COMMENT '同级复现次数',
  `reopen_reason` VARCHAR(300) NULL COMMENT '最近重开原因',
  `create_date_time` BIGINT NULL,
  `create_date` INT NULL,
  `create_time` INT NULL,
  `create_year` INT NULL,
  `create_month` INT NULL,
  `create_day` INT NULL,
  `create_hour` INT NULL,
  `create_minute` INT NULL,
  `create_second` INT NULL,
  `create_week` INT NULL,
  `update_date_time` BIGINT NULL,
  `update_date` INT NULL,
  `update_time` INT NULL,
  `update_year` INT NULL,
  `update_month` INT NULL,
  `update_day` INT NULL,
  `update_hour` INT NULL,
  `update_minute` INT NULL,
  `update_second` INT NULL,
  `update_week` INT NULL,
  PRIMARY KEY (`risk_id`),
  UNIQUE KEY `uk_risk_item_alert_key` (`com_id`, `alert_key`),
  KEY `idx_risk_item_company` (`com_id`, `risk_id`),
  KEY `idx_risk_item_company_store` (`com_id`, `store_id`, `risk_id`),
  KEY `idx_risk_item_company_team` (`com_id`, `team_id`, `risk_id`),
  KEY `idx_risk_item_company_owner` (`com_id`, `owner_id`, `risk_id`),
  KEY `idx_risk_item_company_status_due` (`com_id`, `status`, `due_at`),
  KEY `idx_risk_item_company_project` (`com_id`, `project_id`, `risk_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='风险处置单';

CREATE TABLE IF NOT EXISTS `db_risk_disposition_log` (
  `log_id` BIGINT NOT NULL COMMENT '处置流水索引（雪花）',
  `com_id` BIGINT NOT NULL COMMENT '所属企业',
  `risk_id` BIGINT NOT NULL COMMENT '所属处置单',
  `action` VARCHAR(20) NOT NULL COMMENT 'Assign/Claim/Comment/Urge/Close/Reopen/Void',
  `from_status` VARCHAR(20) NULL,
  `to_status` VARCHAR(20) NULL,
  `operator_id` BIGINT NULL COMMENT '操作人',
  `note` VARCHAR(500) NULL COMMENT '处置说明',
  `occurred_at` DATETIME NULL COMMENT '发生时间',
  `create_date_time` BIGINT NULL,
  `create_date` INT NULL,
  `create_time` INT NULL,
  `create_year` INT NULL,
  `create_month` INT NULL,
  `create_day` INT NULL,
  `create_hour` INT NULL,
  `create_minute` INT NULL,
  `create_second` INT NULL,
  `create_week` INT NULL,
  `update_date_time` BIGINT NULL,
  `update_date` INT NULL,
  `update_time` INT NULL,
  `update_year` INT NULL,
  `update_month` INT NULL,
  `update_day` INT NULL,
  `update_hour` INT NULL,
  `update_minute` INT NULL,
  `update_second` INT NULL,
  `update_week` INT NULL,
  PRIMARY KEY (`log_id`),
  KEY `idx_risk_log_company` (`com_id`, `log_id`),
  KEY `idx_risk_log_company_risk` (`com_id`, `risk_id`, `log_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='风险处置流水（append-only，不可修改删除）';

CREATE TABLE IF NOT EXISTS `db_risk_log_evidence` (
  `log_id` BIGINT NOT NULL,
  `evidence_url` VARCHAR(512) NULL,
  KEY `idx_risk_log_evidence_log` (`log_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='风险处置凭证';

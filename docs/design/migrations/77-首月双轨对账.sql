-- 77-首月双轨对账.sql
-- 目的：首月双轨对账批次、四主题明细与附件。
-- 口径：只对项目未收/项目未付/资金余额/项目成本四个主题；原账只读对照，装得清金额只读，差异必须分类。

create table if not exists carryover_reconciliation (
    reconciliation_id bigint not null,
    com_id bigint not null,
    batch_id bigint not null,
    as_of_date date not null,
    period_start date not null,
    period_end date not null,
    status varchar(20) not null default 'Draft',
    owner_id bigint null,
    created_by bigint null,
    confirmed_by bigint null,
    confirmed_at datetime(3) null,
    closed_at datetime(3) null,
    remark varchar(500) null,
    create_date_time bigint null,
    create_date int null,
    create_time int null,
    create_year int null,
    create_month int null,
    create_day int null,
    create_hour int null,
    create_minute int null,
    create_second int null,
    create_week int null,
    update_date_time bigint null,
    update_date int null,
    update_time int null,
    update_year int null,
    update_month int null,
    update_day int null,
    update_hour int null,
    update_minute int null,
    update_second int null,
    update_week int null,
    primary key (reconciliation_id),
    key idx_carryover_recon_company (com_id, reconciliation_id),
    key idx_carryover_recon_batch (com_id, batch_id, reconciliation_id),
    constraint fk_carryover_recon_company foreign key (com_id) references db_tenant_company (com_id),
    constraint fk_carryover_recon_batch foreign key (batch_id) references carryover_batch (batch_id),
    constraint fk_carryover_recon_owner foreign key (owner_id) references db_tenant_employee (emp_id),
    constraint fk_carryover_recon_creator foreign key (created_by) references db_tenant_employee (emp_id),
    constraint fk_carryover_recon_confirmer foreign key (confirmed_by) references db_tenant_employee (emp_id)
) engine=InnoDB default charset=utf8mb4 comment='首月双轨对账批次';

create table if not exists carryover_reconciliation_item (
    item_id bigint not null,
    com_id bigint not null,
    reconciliation_id bigint not null,
    theme varchar(20) not null comment 'Receivable/Payable/Cash/Cost',
    original_amount decimal(14,2) null comment '原账金额',
    original_source varchar(500) null comment '原账来源说明',
    original_confirmed tinyint(1) not null default 0 comment '原账金额是否已确认',
    system_amount decimal(14,2) not null default 0 comment '装得清金额',
    difference decimal(14,2) null comment '差异 = 原账 - 装得清',
    difference_type varchar(20) null comment '差异分类',
    difference_status varchar(20) not null default 'Pending' comment '差异状态',
    reason varchar(500) null comment '差异原因',
    action varchar(500) null comment '处理动作',
    owner_id bigint null comment '责任人',
    due_date date null comment '处理时限',
    create_date_time bigint null,
    create_date int null,
    create_time int null,
    create_year int null,
    create_month int null,
    create_day int null,
    create_hour int null,
    create_minute int null,
    create_second int null,
    create_week int null,
    update_date_time bigint null,
    update_date int null,
    update_time int null,
    update_year int null,
    update_month int null,
    update_day int null,
    update_hour int null,
    update_minute int null,
    update_second int null,
    update_week int null,
    primary key (item_id),
    unique key uk_carryover_recon_theme (reconciliation_id, theme),
    key idx_carryover_recon_item_company (com_id, reconciliation_id, theme),
    key idx_carryover_recon_item_owner (com_id, owner_id, item_id),
    constraint fk_carryover_recon_item_company foreign key (com_id) references db_tenant_company (com_id),
    constraint fk_carryover_recon_item_recon foreign key (reconciliation_id) references carryover_reconciliation (reconciliation_id),
    constraint fk_carryover_recon_item_owner foreign key (owner_id) references db_tenant_employee (emp_id)
) engine=InnoDB default charset=utf8mb4 comment='首月双轨对账主题';


-- 63 AI调用与企业、门店影子用量底账
-- 依据：docs/product/2026-09-26-AI资源用量基础统计P0产品需求规格.md
-- 说明：P0 只记录调用、资源单位、影子点数和归属，不扣真实资源包、不修改订阅剩余天数。
-- 适用：MySQL 8.0+。执行前备份。

CREATE TABLE IF NOT EXISTS `db_ai_usage_call` (
  `call_id` BIGINT NOT NULL COMMENT 'AI调用记录索引（雪花）',
  `com_id` BIGINT NOT NULL COMMENT '所属企业',
  `business_store_id` BIGINT NULL COMMENT '业务对象所属门店',
  `employee_store_id` BIGINT NULL COMMENT '执行员工所属门店',
  `allocation_store_id` BIGINT NULL COMMENT '统计分摊门店；空为企业公共',
  `allocation_type` VARCHAR(24) NOT NULL COMMENT 'BusinessStore/EmployeeStore/EnterprisePublic',
  `allocation_rule_version` VARCHAR(24) NULL COMMENT '门店归属规则版本',
  `employee_id` BIGINT NULL COMMENT '触发员工；系统调用可空',
  `request_id` VARCHAR(96) NULL COMMENT '上游请求标识',
  `idempotency_key` VARCHAR(160) NOT NULL COMMENT '幂等键，同企业唯一',
  `business_module` VARCHAR(32) NOT NULL COMMENT '业务模块',
  `capability_code` VARCHAR(64) NOT NULL COMMENT 'AI能力编码',
  `scene_code` VARCHAR(64) NULL COMMENT '业务场景编码',
  `business_type` VARCHAR(40) NULL COMMENT '关联业务对象类型',
  `business_id` BIGINT NULL COMMENT '关联业务对象主键',
  `provider_code` VARCHAR(64) NULL COMMENT '模型或服务供应方',
  `model_code` VARCHAR(64) NULL COMMENT '模型编码',
  `model_version` VARCHAR(64) NULL COMMENT '模型版本',
  `capability_version` VARCHAR(64) NULL COMMENT '能力版本',
  `rate_card_version` VARCHAR(32) NULL COMMENT '影子费率版本，不代表正式收费费率',
  `input_units` BIGINT NOT NULL DEFAULT 0 COMMENT '输入资源单位',
  `output_units` BIGINT NOT NULL DEFAULT 0 COMMENT '输出资源单位',
  `resource_units` BIGINT NOT NULL DEFAULT 0 COMMENT '资源单位合计',
  `shadow_billable_units` BIGINT NOT NULL DEFAULT 0 COMMENT '影子计费点数',
  `refunded_units` BIGINT NOT NULL DEFAULT 0 COMMENT '返还影子点数',
  `platform_cost` BIGINT NULL COMMENT '平台实际成本（分），仅平台运营使用',
  `estimated` BIT(1) NOT NULL DEFAULT b'0' COMMENT '资源单位是否为估算值',
  `status` VARCHAR(24) NOT NULL COMMENT 'Requested/Validated/Reserved/Running/Succeeded/Failed/Cancelled/Expired/DuplicateBlocked',
  `billing_status` VARCHAR(24) NOT NULL COMMENT 'Pending/Calculated/Returned/Void/Adjusted',
  `failure_code` VARCHAR(64) NULL COMMENT '失败分类',
  `failure_message` VARCHAR(300) NULL COMMENT '失败说明，不保存敏感正文',
  `started_at` DATETIME(6) NOT NULL COMMENT '调用开始时间',
  `completed_at` DATETIME(6) NULL COMMENT '调用完成时间',
  `duration_ms` BIGINT NULL COMMENT '调用耗时（毫秒）',
  `retry_of_call_id` BIGINT NULL COMMENT '重试来源记录',
  `cancel_reason` VARCHAR(300) NULL COMMENT '取消原因',
  `create_date_time` BIGINT NULL,
  `create_date` INT NULL,
  `create_time` INT NULL,
  `create_year` INT NULL,
  `create_month` INT NULL,
  `create_day` INT NULL,
  `create_hour` INT NULL,
  `create_minute` INT NULL,
  `create_second` INT NULL,
  `create_week` TINYINT NULL,
  `update_date_time` BIGINT NULL,
  `update_date` INT NULL,
  `update_time` INT NULL,
  `update_year` INT NULL,
  `update_month` INT NULL,
  `update_day` INT NULL,
  `update_hour` INT NULL,
  `update_minute` INT NULL,
  `update_second` INT NULL,
  `update_week` TINYINT NULL,
  PRIMARY KEY (`call_id`),
  UNIQUE KEY `uk_ai_usage_call_idempotency` (`com_id`, `idempotency_key`),
  KEY `idx_ai_usage_call_company_time` (`com_id`, `started_at`, `call_id`),
  KEY `idx_ai_usage_call_store_time` (`com_id`, `allocation_store_id`, `started_at`),
  KEY `idx_ai_usage_call_capability_time` (`com_id`, `capability_code`, `started_at`),
  KEY `idx_ai_usage_call_module_time` (`com_id`, `business_module`, `started_at`),
  KEY `idx_ai_usage_call_business` (`com_id`, `business_type`, `business_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI调用与企业门店影子用量底账';
